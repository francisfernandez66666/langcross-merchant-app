-- ── 004 · 菜品图片 ────────────────────────────────────────────
--
-- 客人在国外看不懂菜名，**图比译文更直接影响点单**：一张图能让客人不问店员就
-- 指给同伴看。此前 dish 表没有任何图片字段，客人端只能给出「名字 + 价格」，
-- 对跨境客流是硬缺口。
--
-- 设计取舍：
--   1) 存 URL 而不是二进制：图片可以来自「商家上传」也可以来自「外部图床」，
--      存 URL 让两种来源共用一条渲染路径，数据库不背大对象。
--   2) 空串 = 无图（与 COALESCE 折叠成的空串一致），不用 NULL 便于 SQL 判断。
--   3) upload 目录用 LC_UPLOAD_DIR 配置，迁移不涉及文件系统；生产换成对象存储时
--      只需替换上传实现，接口契约不变（见「图片存储的接缝」）。

ALTER TABLE dish ADD COLUMN IF NOT EXISTS image_url TEXT NOT NULL DEFAULT '';

COMMENT ON COLUMN dish.image_url IS '菜品图片 URL（空串=无图；客人端渲染占位块）';
